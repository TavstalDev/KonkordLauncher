namespace Tavstal.KonkordLauncher.Desktop.Constants;

/// <summary>
///     Bitmap widths used by the UI.
/// </summary>
public static class BitmapSizes
{
    /// <summary>
    ///     Width of an instance icon in the instance list and play card.
    /// </summary>
    public const int InstanceModel = 72;

    /// <summary>
    ///     Width of an icon in the icon selector.
    /// </summary>
    public const int IconSelectorIcon = InstanceModel;

    /// <summary>
    ///     Width of a Modrinth project icon in the search lists.
    /// </summary>
    public const int ProjectIcon = 35;

    /// <summary>
    ///     Width of a mod icon in the mods table.
    /// </summary>
    public const int ModIcon = 32;

    /// <summary>
    ///     Width of a resource pack icon in the resource packs table.
    /// </summary>
    public const int ResourcePackIcon = 32;

    /// <summary>
    ///     Width of a shader pack icon in the shader packs table.
    /// </summary>
    public const int ShaderPackIcon = 32;

    /// <summary>
    ///     Width of a world icon in the worlds table.
    /// </summary>
    public const int WorldIcon = 48;

    /// <summary>
    ///     Width of a server icon in the servers table.
    /// </summary>
    public const int ServerIcon = 48;

    /// <summary>
    ///     Width of a screenshot preview in the screenshots table.
    /// </summary>
    public const int ScreenshotIcon = 48;

    /// <summary>
    ///     Width of the fallback image for worlds and other resources.
    /// </summary>
    public const int DefaultWorldIcon = WorldIcon;

    /// <summary>
    ///     Width of an account avatar in the sidebar.
    /// </summary>
    public const int AccountAvatar = 55;

    /// <summary>
    ///     Width of the 2D skin preview in the skin download view.
    /// </summary>
    public const int SkinPreview = 138;

    /// <summary>
    ///     Width of a cape in the cape card.
    /// </summary>
    public const int CapePreview = 86;
}
