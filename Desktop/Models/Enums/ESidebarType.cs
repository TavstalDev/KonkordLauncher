namespace Tavstal.KonkordLauncher.Desktop.Models.Enums;

/// <summary>
/// Represents the different types of sidebar options available in the application.
/// </summary>
public enum ESidebarType
{
    /// <summary>
    /// The "Play" sidebar option.
    /// </summary>
    Play = 0,

    /// <summary>
    /// The "News" sidebar option, displaying news and updates.
    /// </summary>
    News = 1,

    /// <summary>
    /// The "Accounts" sidebar option, for managing user accounts.
    /// </summary>
    Accounts = 2,

    /// <summary>
    /// The "Settings" sidebar option, for configuring application settings.
    /// </summary>
    Settings = 3
}